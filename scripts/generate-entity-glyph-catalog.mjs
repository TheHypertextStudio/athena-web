import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFile } from 'node:fs/promises';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const uiRequire = createRequire(resolve(repositoryRoot, 'packages/ui/package.json'));
const materialVersions = uiRequire('@material-symbols/metadata/versions.json');
const emoji = uiRequire('emojibase-data/en/compact.json');

const materialNames = Object.keys(materialVersions);
const fullyQualifiedEmoji = emoji.filter((entry) => entry.group !== undefined);
const emojiHexcodes = fullyQualifiedEmoji.flatMap((entry) => [
  entry.hexcode,
  ...(entry.skins ?? []).map((skin) => skin.hexcode),
]);

const generatedHeader = `/**
 * Generated entity glyph catalog. Do not edit this file by hand.
 *
 * @remarks
 * Run \`pnpm glyphs:generate\` after changing either pinned catalog package.
 */\n`;

function typescriptStringArray(values) {
  return `[\n${values.map((value) => `  '${value}',`).join('\n')}\n]`;
}

await writeFile(
  resolve(repositoryRoot, 'domains/work/src/generated/material-symbol-names.ts'),
  `${generatedHeader}
/** Every symbol name supplied by the pinned Material Symbols metadata package. */
export const MATERIAL_SYMBOL_NAMES: readonly string[] = ${typescriptStringArray(materialNames)};

const MATERIAL_SYMBOL_NAME_SET: ReadonlySet<string> = new Set(MATERIAL_SYMBOL_NAMES);

/** Return whether a string names a glyph in the pinned Material Symbols catalog. */
export function isKnownMaterialSymbolName(value: string): boolean {
  return MATERIAL_SYMBOL_NAME_SET.has(value);
}\n`,
);

await writeFile(
  resolve(repositoryRoot, 'domains/work/src/generated/emoji-hexcodes.ts'),
  `${generatedHeader}
/** Every base and skin-tone sequence supplied by the pinned English Emojibase compact dataset. */
export const EMOJI_HEXCODES: readonly string[] = ${typescriptStringArray(emojiHexcodes)};

const EMOJI_HEXCODE_SET: ReadonlySet<string> = new Set(EMOJI_HEXCODES);

/** Return whether a string names one emoji in the pinned Unicode catalog. */
export function isKnownEmojiHexcode(value: string): boolean {
  return EMOJI_HEXCODE_SET.has(value);
}\n`,
);

console.log(`Generated ${materialNames.length} symbols and ${emojiHexcodes.length} emoji sequences.`);
